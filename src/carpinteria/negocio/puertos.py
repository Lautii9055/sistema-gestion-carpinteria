"""Contratos que la capa de negocio necesita de la capa de datos.

La lógica depende de estas interfaces y no de SQL Server (principio de
inversión de dependencias, la "D" de SOLID). Por eso las pruebas pueden usar
repositorios en memoria y la lógica se prueba sin una base de datos.
"""
from datetime import datetime
from decimal import Decimal
from typing import Protocol

from carpinteria.negocio.entidades import (Cliente, ClienteResumen, EventoAuditoria, Obra,
                                          TipoEvento, TrabajoResumen, Usuario)


class RepositorioUsuarios(Protocol):
    def buscar_por_nombre(self, nombre_usuario: str) -> Usuario | None: ...
    def buscar_por_id(self, id_usuario: int) -> Usuario | None: ...
    def registrar_fallo(self, id_usuario: int, intentos: int, bloqueado_hasta: datetime | None) -> None: ...
    def registrar_ingreso_exitoso(self, id_usuario: int, fecha: datetime) -> None: ...
    def cambiar_contrasena(self, id_usuario: int, hash_contrasena: str, fecha: datetime) -> None: ...
    def listar(self) -> list[Usuario]: ...
    def crear(self, nombre_usuario: str, nombre_completo: str, hash_contrasena: str) -> int: ...
    def asignar_contrasena_provisoria(self, id_usuario: int, hash_contrasena: str) -> None: ...
    def cambiar_estado(self, id_usuario: int, activo: bool) -> None: ...


class RepositorioAuditoria(Protocol):
    def registrar(self, codigo_evento: str, *, id_usuario: int | None = None,
                  usuario_ingresado: str | None = None, entidad: str | None = None,
                  id_entidad: int | None = None, detalle: str | None = None,
                  equipo: str | None = None) -> None: ...
    def contar_ingresos_fallidos(self, id_usuario: int, desde: datetime | None) -> int: ...
    def listar(self, *, desde: datetime | None = None, id_usuario: int | None = None,
               codigo_evento: str | None = None, solo_criticos: bool = False,
               limite: int = 500) -> list[EventoAuditoria]: ...
    def tipos_de_evento(self) -> list[TipoEvento]: ...


class RepositorioParametros(Protocol):
    def obtener(self, clave: str) -> Decimal | None: ...


class RepositorioClientes(Protocol):
    def buscar(self, terminos: list[str], incluir_inactivos: bool, limite: int) -> list[ClienteResumen]: ...
    def obtener(self, id_cliente: int) -> Cliente | None: ...
    def buscar_por_telefono(self, digitos: str) -> list[Cliente]: ...
    def crear(self, cliente: Cliente, obra_inicial: Obra | None) -> int: ...
    def actualizar(self, cliente: Cliente) -> None: ...
    def cambiar_estado(self, id_cliente: int, activo: bool) -> None: ...


class RepositorioObras(Protocol):
    def listar_por_cliente(self, id_cliente: int) -> list[Obra]: ...
    def existe(self, id_cliente: int, direccion: str, localidad: str, excluir_id: int | None) -> bool: ...
    def crear(self, obra: Obra) -> int: ...
    def actualizar(self, obra: Obra) -> None: ...
    def trabajos_de_la_obra(self, id_obra: int) -> list[TrabajoResumen]: ...
